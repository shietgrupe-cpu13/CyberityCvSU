/** Collect only the references a lesson actually cites; unknown IDs fail immediately. */
internal fun reviewedLesson(levelId: Int, title: String, pages: List<LessonPage>,
                            questions: List<LessonQuestion>): Lesson = Lesson(
    levelId, title, pages,
    pages.flatMap { it.sourceIds }.distinct().map { reviewedLessonSources.getValue(it) }, questions
)

internal fun lessonEvidence(title: String, lines: List<String>) = LessonVisual.Log(
    title, lines, caption = "Fictional teaching example, separate from the lab evidence."
)
